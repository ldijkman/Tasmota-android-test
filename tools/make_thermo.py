"""Zet het thermostaat-script van de website in de app (assets/thermostat-script.js).
Bron: site/shelly-thermostat-example.js. Draai dit na elke wijziging aan het script."""
import json, os
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
code = open(os.path.join(root, 'site', 'shelly-thermostat-example.js'), encoding='utf-8').read()
out = os.path.join(root, 'plafond-led-app', 'app', 'src', 'main', 'assets', 'thermostat-script.js')
open(out, 'w', encoding='utf-8').write('// generated by tools/make_thermo.py from site/shelly-thermostat-example.js\nwindow.SH_THERMO_CODE = ' + json.dumps(code) + ';\n')
print('written', out, len(code), 'chars')
